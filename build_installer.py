#!/usr/bin/env python3
"""Embed audited assets into the single curl-installable script."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent
assets = {p.name: p.read_text() for p in sorted((root / "files").iterdir()) if p.is_file()}
source = (root / "installer.py").read_text()
footer = "\ntry:\n    main(" + repr(assets) + ")\nexcept Exception as error:\n    print('Installation failed: ' + str(error), file=sys.stderr)\n    sys.exit(1)\n"
(root / "install.sh").write_text("#!/usr/bin/env bash\n# Generated by build_installer.py; AGNOS root filesystem remains read-only.\nset -eu\npython3 - \"$@\" <<'OPENPILOT_TAILSCALE_PY'\n" + source + footer + "OPENPILOT_TAILSCALE_PY\n")
(root / "install.sh").chmod(0o755)
